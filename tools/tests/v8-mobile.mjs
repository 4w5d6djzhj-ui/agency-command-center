import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const base = process.argv[2], out = process.argv[3]; const b = await chromium.launch(); const errs = [];
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true }); const p = await ctx.newPage();
p.on('pageerror', e => errs.push('PAGEERROR ' + e.message));
await p.goto(base, { waitUntil: 'networkidle' });
const g = p.locator('button.gate-accept'); if (await g.count()) await g.click(); await p.waitForSelector('.topbar');
await p.evaluate(() => document.fonts.ready); await p.waitForTimeout(1000);
await p.screenshot({ path: out + 'm-today.png' });
await p.evaluate(() => window.scrollTo(0, 900)); await p.waitForTimeout(300);
await p.screenshot({ path: out + 'm-today-scrolled.png' });
const ov = await p.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
await p.locator('.tabs button:text-is("Compose")').click(); await p.waitForTimeout(600);
await p.screenshot({ path: out + 'm-compose.png' });
const ov2 = await p.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
await p.locator('.x-nowbar').click(); await p.waitForTimeout(500);
const tabNow = await p.locator('.tabs button.active').innerText();
await p.locator('.x-planlink', { hasText: 'Day plan' }).click(); await p.waitForTimeout(500);
await p.screenshot({ path: out + 'm-plan.png' });
const ov3 = await p.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
console.log('overflow today/compose/plan', ov, ov2, ov3, '| nowbar took us to', tabNow);
console.log(errs.length ? errs.join('\n') : 'no errors'); await b.close();
